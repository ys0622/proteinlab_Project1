for (const [slug, nutrition] of Object.entries(exactNutritionBySlug)) {
  nutritionBySlug.set(slug, nutrition);
}

function roundToSingleDecimal(value: number) {
  return Math.round(value * 10) / 10;
}

function buildNutrition(product: BarProduct): NutritionPerBottle {
  const rawPatch = nutritionBySlug.get(product.slug) ?? {};
  // 2026-10-14 성분표 대조(docs/bar-label-audit-2026-10-14.md): JSON에 지방이 들어 있으면 라벨로 확인한 값이라
  // 열량·단백질·당류·지방·나트륨은 JSON을 우선한다. 묶음(addGroup) 보정값은 맛별 라벨이 아니라 탄수화물 등도 쓰지 않는다.
  const labelVerified = product.fat != null;
  const isGroupPatch = !(product.slug in exactNutritionBySlug);
  const patch: NutritionPatch = labelVerified && isGroupPatch ? {} : rawPatch;
  const pick = <T,>(fromJson: T | undefined, fromPatch: T | undefined) =>
    labelVerified ? (fromJson ?? fromPatch) : (fromPatch ?? fromJson);

  const caloriesKcal = pick(product.calories, patch.caloriesKcal);
  const proteinG = pick(product.proteinPerServing, patch.proteinG);
  const sugarsG = pick(product.sugar, patch.sugarsG);
  const fatG = pick(product.fat, patch.fatG);
  const sodiumMg = pick(product.sodium, patch.sodiumMg);

  const derivedCarbs =
    caloriesKcal != null && proteinG != null && fatG != null
      ? roundToSingleDecimal(Math.max(0, (caloriesKcal - proteinG * 4 - fatG * 9) / 4))
      : undefined;

  return {
    caloriesKcal,
    proteinG,
    carbsG: patch.carbsG ?? derivedCarbs,
    sugarsG,
    fatG,
    satFatG: patch.satFatG ?? 0,
    sodiumMg,
    fiberG: patch.fiberG,
    cholesterolMg: patch.cholesterolMg,
    transFatG: patch.transFatG,
  };
}

function enrichBarProduct(product: BarProduct): BarProduct {
  const nutritionPerBottle = buildNutrition(product);
  const calories = nutritionPerBottle.caloriesKcal ?? product.calories;
  const proteinPerServing = nutritionPerBottle.proteinG ?? product.proteinPerServing;
  const sugar = nutritionPerBottle.sugarsG ?? product.sugar;
  const fat = nutritionPerBottle.fatG ?? product.fat;
  const sodium = nutritionPerBottle.sodiumMg ?? product.sodium;
  const servingAudit = barServingAuditBySlug[product.slug];
  const density =
    calories && proteinPerServing
      ? `${roundToSingleDecimal((proteinPerServing / calories) * 100)}g/100kcal`
      : product.density;

  return {
    ...product,
    productType: "bar" as const,
    nutritionBasis: servingAudit?.nutritionBasis ?? "per_unit",
    needsServingCheck: servingAudit?.needsServingCheck ?? false,
    servingCheckNote: servingAudit?.note,
    calories,
    proteinPerServing,
    sugar,
    fat,
    sodium,
    density,
    nutritionPerBottle,
  };
}

export function getBarProducts(): ProductDetailProps[] {
  return (barData as ProductDetailProps[]).map(enrichBarProduct).map(withCoupangUrl);
}

